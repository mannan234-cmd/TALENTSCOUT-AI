from __future__ import annotations

from typing import List, Tuple

from app.models.opportunity import Opportunity
from app.models.opportunity_duplicate_resolution import (
    OpportunityDuplicateResolutionResult,
)
from app.services.opportunity_duplicate_resolution_pipeline_service import (
    OpportunityDuplicateResolutionPipelineService,
)
from app.services.opportunity_quality_control_service import (
    OpportunityQualityControlService,
)
from app.services.opportunity_validation_service import (
    OpportunityValidationService,
)
from app.services.opportunity_identity_service import (
    OpportunityIdentityService,
)
from app.services.supabase_service import SupabaseService


class OpportunityServiceError(ValueError):
    """Raised when an opportunity service operation cannot be completed."""


class OpportunityService:
    """
    Application-level orchestration for canonical opportunities.

    This service coordinates existing Phase 5 domain services.
    It does not perform student matching, ranking, recommendation,
    or decision-making.
    """

    @staticmethod
    def validate(opportunity: Opportunity) -> Opportunity:
        if not isinstance(opportunity, Opportunity):
            raise OpportunityServiceError(
                "Expected an Opportunity instance."
            )

        validated = OpportunityValidationService.validate(opportunity)

        if not isinstance(validated, Opportunity):
            raise OpportunityServiceError(
                "Opportunity validation did not return an Opportunity."
            )

        return validated

    @classmethod
    def quality_check(cls, opportunity: Opportunity):
        opportunity = cls.validate(opportunity)
        return OpportunityQualityControlService.check(opportunity)

    @classmethod
    def prepare(
        cls,
        opportunities: List[Opportunity],
    ) -> Tuple[
        List[Opportunity],
        List[OpportunityDuplicateResolutionResult],
    ]:
        """
        Validate, quality-check, and deterministically resolve duplicates.

        Returns canonical opportunities and duplicate-resolution results.
        """
        if opportunities is None:
            raise OpportunityServiceError(
                "Opportunities cannot be None."
            )

        if not isinstance(opportunities, list):
            raise OpportunityServiceError(
                "Opportunities must be a list."
            )

        validated: List[Opportunity] = []

        for opportunity in opportunities:
            validated_opportunity = cls.validate(opportunity)

            quality_result = OpportunityQualityControlService.check(
                validated_opportunity
            )

            if not quality_result.is_valid:
                messages = "; ".join(
                    issue.message for issue in quality_result.issues
                )
                raise OpportunityServiceError(
                    f"Opportunity quality check failed: {messages}"
                )

            # Fingerprint is part of the canonical opportunity identity.
            # Assign it before duplicate resolution and persistence so every
            # prepared Opportunity carries the same deterministic identity.
            fingerprint = OpportunityIdentityService.fingerprint(
                validated_opportunity
            )

            validated.append(
                validated_opportunity.model_copy(
                    update={"fingerprint": fingerprint}
                )
            )

        return OpportunityDuplicateResolutionPipelineService.resolve(
            validated
        )


    @staticmethod
    def _serialize(opportunity: Opportunity) -> dict:
        """
        Convert an Opportunity into a Supabase/PostgREST-safe payload.

        Important boundaries:
        - New UUIDs are generated by PostgreSQL.
        - Existing UUIDs are preserved.
        - HttpUrl values become plain strings.
        - Enum values become their string values.
        - Datetimes become ISO-8601 strings.
        - Fingerprint is always deterministic.
        """
        from enum import Enum
        from datetime import datetime, timezone
        from pydantic import HttpUrl

        raw = opportunity.model_dump(mode="python")

        # PostgreSQL owns UUID generation for new records.
        if opportunity.id is None:
            raw.pop("id", None)
        else:
            raw["id"] = str(opportunity.id)

        # Canonical fingerprint for persistence identity.
        if opportunity.fingerprint:
            raw["fingerprint"] = str(opportunity.fingerprint)
        else:
            from app.services.opportunity_identity_service import (
                OpportunityIdentityService,
            )

            raw["fingerprint"] = OpportunityIdentityService.fingerprint(
                opportunity
            )

        # Database contract: updated_at is NOT NULL.
        # Preserve an existing timestamp; otherwise generate a
        # timezone-aware UTC timestamp at persistence time.
        if opportunity.updated_at is None:
            raw["updated_at"] = datetime.now(timezone.utc)
        else:
            raw["updated_at"] = opportunity.updated_at

        def make_json_safe(value):
            if isinstance(value, HttpUrl):
                return str(value)

            if isinstance(value, Enum):
                return value.value

            if isinstance(value, datetime):
                return value.isoformat()

            if isinstance(value, list):
                return [make_json_safe(item) for item in value]

            if isinstance(value, dict):
                return {
                    str(key): make_json_safe(item)
                    for key, item in value.items()
                }

            return value

        payload = {
            key: make_json_safe(value)
            for key, value in raw.items()
        }

        # Final defensive UUID rule after conversion.
        if payload.get("id") in (None, "None", ""):
            payload.pop("id", None)

        return payload


    @classmethod
    def save(cls, opportunity: Opportunity) -> Opportunity:
        opportunity = cls.prepare_one(opportunity)

        client = SupabaseService().supabase

        payload = cls._serialize(opportunity)

        response = (
            client
            .table("opportunities")
            .upsert(payload, on_conflict="fingerprint")
            .execute()
        )

        if not response.data:
            raise OpportunityServiceError(
                "Supabase did not return the saved opportunity."
            )

        # Supabase owns database-managed fields such as created_at.
        # Opportunity intentionally does not model created_at, so remove
        # DB-only response fields before application-level validation.
        saved_data = dict(response.data[0])
        saved_data.pop("created_at", None)

        return Opportunity.model_validate(saved_data)

    @classmethod
    def get_by_id(cls, opportunity_id: str) -> Opportunity | None:
        if not opportunity_id:
            raise OpportunityServiceError(
                "opportunity_id cannot be empty."
            )

        client = SupabaseService().supabase

        response = (
            client
            .table("opportunities")
            .select("*")
            .eq("id", opportunity_id)
            .limit(1)
            .execute()
        )

        if not response.data:
            return None

        # Supabase owns database-managed fields such as created_at.
        # Remove DB-only response fields before application validation.
        loaded_data = dict(response.data[0])
        loaded_data.pop("created_at", None)

        return Opportunity.model_validate(loaded_data)

    @classmethod
    def delete_by_id(cls, opportunity_id: str) -> bool:
        if not opportunity_id:
            raise OpportunityServiceError(
                "opportunity_id cannot be empty."
            )

        client = SupabaseService().supabase

        response = (
            client
            .table("opportunities")
            .delete()
            .eq("id", opportunity_id)
            .execute()
        )

        return bool(response.data)

    @classmethod
    def prepare_one(cls, opportunity: Opportunity) -> Opportunity:
        canonical, _ = cls.prepare([opportunity])

        if len(canonical) != 1:
            raise OpportunityServiceError(
                "Expected exactly one canonical opportunity."
            )

        return canonical[0]
